-- Criação completa do banco de dados do projeto Acorda RJ.
-- Representa o estado estrutural atual do sistema, sem automação ou
-- disparo de mensagens.
--
-- USO EXCLUSIVO EM BANCO POSTGRESQL VAZIO.
-- Este arquivo falha de propósito se encontrar alguma tabela do projeto.
-- Para atualizar a estrutura, crie antes um backup completo e validado,
-- recrie um banco vazio com este arquivo e restaure somente os dados aprovados.

BEGIN;

SET client_encoding = 'UTF8';
SET standard_conforming_strings = ON;
SET check_function_bodies = FALSE;
SET client_min_messages = WARNING;

DO $$
DECLARE
  objeto_existente TEXT;
BEGIN
  SELECT classe.relname
  INTO objeto_existente
  FROM pg_catalog.pg_class AS classe
  INNER JOIN pg_catalog.pg_namespace AS namespace
    ON namespace.oid = classe.relnamespace
  WHERE namespace.nspname = 'public'
    AND classe.relname IN (
      'aceites_privacidade',
      'backups_banco',
      'bairros',
      'consentimentos',
      'contatos',
      'historico_contatos',
      'importacao_linhas',
      'importacoes',
      'numeros_whatsapp',
      'modelos_mensagem',
      'campanhas',
      'comunicacoes',
      'historico_comunicacoes',
      'campanha_lotes',
      'campanha_participacoes',
      'campanha_tentativas',
      'historico_status_mensageria',
      'configuracoes_sistema',
      'historico_configuracoes_sistema',
      'eventos_webhook_mensageria',
      'sincronizacoes_limite_meta',
      'origens',
      'schema_migrations',
      'eventos',
      'historico_eventos',
      'contato_eventos',
      'solicitacoes_exclusao',
      'tentativas_login',
      'textos_formulario',
      'usuarios'
    )
  LIMIT 1;

  IF objeto_existente IS NOT NULL THEN
    RAISE EXCEPTION
      'Execução recusada: o banco já possui a estrutura do projeto (%). Este arquivo exige um banco vazio.',
      objeto_existente;
  END IF;

  IF to_regprocedure('public.atualizar_data_modificacao()') IS NOT NULL THEN
    RAISE EXCEPTION
      'Execução recusada: a função atualizar_data_modificacao já existe. Use um banco vazio.';
  END IF;
END;
$$;

CREATE FUNCTION public.atualizar_data_modificacao()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
  NEW.atualizado_em = CURRENT_TIMESTAMP;
  RETURN NEW;
END;
$$;

CREATE TABLE public.schema_migrations (
  versao VARCHAR(20) NOT NULL,
  nome_arquivo VARCHAR(255) NOT NULL,
  checksum_sha256 CHAR(64) NOT NULL,
  executada_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT schema_migrations_pkey PRIMARY KEY (versao),
  CONSTRAINT schema_migrations_nome_arquivo_unico UNIQUE (nome_arquivo),
  CONSTRAINT schema_migrations_checksum_formato CHECK (
    checksum_sha256 ~ '^[a-f0-9]{64}$'
  )
);

