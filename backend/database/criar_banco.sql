  CONSTRAINT contatos_bairro_nao_vazio CHECK (
    LENGTH(TRIM(bairro)) >= 2
  ),
  CONSTRAINT contatos_consentimento_armazenamento_obrigatorio CHECK (
    consentimento_armazenamento = TRUE
  ),
  CONSTRAINT contatos_data_consentimento_mensagens CHECK (
    (consentimento_mensagens = TRUE AND consentimento_mensagens_em IS NOT NULL)
    OR
    (consentimento_mensagens = FALSE AND consentimento_mensagens_em IS NULL)
  ),
  CONSTRAINT contatos_idade_valida CHECK (
    idade IS NULL OR idade >= 0
  ),
  CONSTRAINT contatos_nome_valido CHECK (
    nome IS NULL
    OR (
      LENGTH(TRIM(nome)) >= 2
      AND TRIM(nome) ~ '[[:alpha:]]'
    )
  ),
  CONSTRAINT contatos_problema_nao_vazio CHECK (
    LENGTH(TRIM(problema)) >= 3
  ),
  CONSTRAINT contatos_telefone_nao_vazio CHECK (
    LENGTH(TRIM(telefone)) >= 8
  ),
  CONSTRAINT contatos_telefone_normalizado_apenas_numeros CHECK (
    telefone_normalizado ~ '^[0-9]+$'
  ),
  CONSTRAINT contatos_telefone_normalizado_tamanho CHECK (
    LENGTH(telefone_normalizado) BETWEEN 10 AND 15
  )
);

